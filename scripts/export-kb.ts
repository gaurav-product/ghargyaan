/**
 * Export the knowledge base to Supabase seed SQL (items + retrieval chunks).
 * Embeddings are added afterwards by scripts/embed-kb.ts (needs an API key).
 *   npm run kb:export
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { KNOWLEDGE, validateKnowledge } from '../src/kb';

const errs = validateKnowledge();
if (errs.length) {
  console.error(errs);
  process.exit(1);
}
const q = (v: unknown) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => (v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`);
const arr = (v: string[]) => `array[${v.map(q).join(',')}]::text[]`;

const lines: string[] = ['-- Generated by scripts/export-kb.ts. Do not edit by hand.', 'begin;', 'delete from public.knowledge_chunks;', 'delete from public.knowledge_items;'];
for (const k of KNOWLEDGE) {
  lines.push(
    `insert into public.knowledge_items (id,title,title_hi,category,situation_label,problem,audience,age_range,modern_guidance,evidence_level,evidence_summary,how_to,what_to_avoid,watch_for,contraindications,red_flags,when_to_seek_help,traditional_use,audience_notes,not_for,clarify,myth,safety_level,source,source_type,last_reviewed,review_status,language,keywords) values (${[
      q(k.id), q(k.title), q(k.title_hi), q(k.category), q(k.situation_label), q(k.problem), arr(k.audience), q(k.age_range), q(k.modern_guidance), q(k.evidence_level), q(k.evidence_summary),
      j(k.how_to), j(k.what_to_avoid), j(k.watch_for), j(k.contraindications), j(k.red_flags), j(k.when_to_seek_help), j(k.traditional_use), j(k.audience_notes), j(k.not_for), j(k.clarify), j(k.myth),
      q(k.safety_level), j(k.source), q(k.source_type), q(k.last_reviewed), q(k.review_status), q(k.language), arr(k.keywords),
    ].join(',')});`,
  );
  const chunks: [string, string][] = [
    ['summary', `${k.title}. ${k.situation_label}. ${k.modern_guidance}`],
    ['problem', k.problem],
    ['keywords', k.keywords.join(' ')],
  ];
  if (k.myth) chunks.push(['myth', `${k.myth.claim} ${k.myth.verdict}`]);
  for (const [kind, content] of chunks) lines.push(`insert into public.knowledge_chunks (item_id,kind,content) values (${q(k.id)},${q(kind)},${q(content)});`);
}
lines.push('commit;');
mkdirSync('supabase', { recursive: true });
writeFileSync('supabase/seed.sql', lines.join('\n') + '\n');
writeFileSync('supabase/knowledge.json', JSON.stringify(KNOWLEDGE, null, 2));
console.log(`Exported ${KNOWLEDGE.length} guides to supabase/seed.sql and supabase/knowledge.json`);
